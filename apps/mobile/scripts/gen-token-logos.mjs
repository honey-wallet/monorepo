// Extracts the token logos the app uses from @iconify-json/cryptocurrency-color
// (CC0) into src/components/wallet/token-logos.ts, so only these SVGs are bundled.
// Run from apps/mobile: `node scripts/gen-token-logos.mjs`, then `pnpm format`.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const SYMBOLS = ['btc', 'eth', 'sol', 'trx', 'xrp', 'usdc', 'usdt', 'generic'];

// The pack predates some rebrands; these replace its logos with the current marks.
const OVERRIDES = {
  // Solana's current mark: three bars with the purple → green gradient on a black disc.
  sol: `<defs><linearGradient id="sol-g" x1="0" y1="1" x2="1" y2="0"><stop offset="0" stop-color="#9945FF"/><stop offset="1" stop-color="#14F195"/></linearGradient></defs><circle cx="16" cy="16" r="16" fill="#000"/><g fill="url(#sol-g)"><path d="M10.6 9.3h13.6l-2.8 3.2H7.8z"/><path d="M7.8 14.4h13.6l2.8 3.2H10.6z"/><path d="M10.6 19.5h13.6l-2.8 3.2H7.8z"/></g>`,
};

const require = createRequire(import.meta.url);
const set = JSON.parse(
  readFileSync(require.resolve('@iconify-json/cryptocurrency-color/icons.json'), 'utf8'),
);
const size = set.width ?? 32;

const entries = SYMBOLS.map((symbol) => {
  const body = OVERRIDES[symbol] ?? set.icons[symbol]?.body;
  if (!body) throw new Error(`No "${symbol}" icon in cryptocurrency-color`);
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}">${body}</svg>`;
  return `  ${symbol.toUpperCase()}: ${JSON.stringify(svg)},`;
});

writeFileSync(
  new URL('../src/components/wallet/token-logos.ts', import.meta.url),
  `// Generated by scripts/gen-token-logos.mjs from @iconify-json/cryptocurrency-color
// (CC0, github.com/atomiclabs/cryptocurrency-icons). Do not edit by hand.

/** Full-colour coin logos keyed by ticker; GENERIC is the fallback coin. */
export const TOKEN_LOGOS: Record<string, string> = {
${entries.join('\n')}
};
`,
);
console.log(`Wrote ${SYMBOLS.length} token logos.`);
